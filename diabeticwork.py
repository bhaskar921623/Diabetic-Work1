img = cv2.resize(img, (640, 640))
img_norm = img / 255.0

input_tensor = torch.tensor(img_norm.transpose(2, 0, 1)).unsqueeze(0).float().to(device)

# -----------------------------
# 3. Normalize Function
# -----------------------------
def normalize(x):
    return (x - x.min()) / (x.max() - x.min() + 1e-8)

# -----------------------------
# 4. Perturbation Map
# -----------------------------
def get_perturbation_map(img, model, patch=40):
    heatmap = np.zeros((640,640))

    for y in range(0,640,patch):
        for x in range(0,640,patch):
            occluded = img.copy()
            occluded[y:y+patch, x:x+patch] = 0

            res = model(occluded, device=device, verbose=False)

            score = 0
            for r in res:
                if len(r.boxes) > 0:
                    score = float(r.boxes.conf.max())

            heatmap[y:y+patch, x:x+patch] = score

    return heatmap

print("Generating Perturbation Map...")
P = normalize(get_perturbation_map(img, model))

# -----------------------------
# 5. Attention Map
# -----------------------------
attention_maps = []

def attn_hook(module, input, output):
    attention_maps.append(output)

