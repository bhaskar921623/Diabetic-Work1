import numpy as np

def compute_entropy(fmap):
    fmap = fmap.flatten()
    fmap = fmap - fmap.min()
    fmap = fmap / (fmap.max() + 1e-6)

    hist, _ = np.histogram(fmap, bins=50, density=True)
    hist = hist + 1e-8

    return -np.sum(hist * np.log(hist))

